export const normalizeAppState = (rawState: any): AppState => {
  if (!rawState || typeof rawState !== 'object') return initialAppState;

  const athletes: Athlete[] = Array.isArray(rawState.athletes) && rawState.athletes.length > 0
    ? rawState.athletes.map((a: Athlete) => {
        const isComplete = a.docStatus === 'Lengkap';
        const docChecklist = a.docChecklist || {
          suratPembebasan: isComplete,
          aktaIjazahKtp: isComplete,
          suketKesehatan: isComplete,
        };
        return {
          ...a,
          docChecklist: {
            suratPembebasan: docChecklist.suratPembebasan ?? isComplete,
            aktaIjazahKtp: docChecklist.aktaIjazahKtp ?? isComplete,
            suketKesehatan: docChecklist.suketKesehatan ?? isComplete,
            notes: docChecklist.notes || '',
          },
        };
      })
    : initialAppState.athletes;

  let checklists: ChecklistItem[] = Array.isArray(rawState.checklists) && rawState.checklists.length > 0
    ? rawState.checklists
    : defaultChecklists;

  const hasDocItems = checklists.some((c) => c.category === 'dokumen');
  if (!hasDocItems) {
    const docItems = defaultChecklists.filter((c) => c.category === 'dokumen');
    const perlengkapanItems = checklists.map((c) => ({ ...c, category: 'perlengkapan' }));
    checklists = [...docItems, ...perlengkapanItems];
  }

  const matches: MatchSchedule[] = Array.isArray(rawState.matches) && rawState.matches.length > 0
    ? rawState.matches
    : defaultMatches;

  return {
    ...initialAppState,
    ...rawState,
    athletes,
    checklists,
    matches,
    lastUpdated: rawState.lastUpdated || new Date().toISOString(),
  };
};
